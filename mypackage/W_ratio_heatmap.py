def assign_continent_dynamic(df, geo_cache=None):
    """
    使用动态地理编码分配大洲

    参数:
        df: DataFrame, 包含x, y坐标列
        geo_cache: dict, 地理编码缓存（可选）

    返回:
        df: 添加continent列的DataFrame
    """
    if geo_cache is None:
        geo_cache = {}

    # 准备坐标（注意：reverse_geocoder需要lat, lon顺序）
    coords = list(zip(df['y'], df['x']))

    # 坐标降维（保留1位小数，减少缓存体积）
    coords_keys = [f"{round(lat, 1)},{round(lon, 1)}" for lat, lon in coords]

    # 查询未缓存的坐标
    new_keys = list(set(key for key in coords_keys if key not in geo_cache))

    if new_keys:
        new_coords = [tuple(map(float, k.split(','))) for k in new_keys]

        # 分块查询（避免内存溢出）
        chunk_size = 5000
        results = []

        for i in range(0, len(new_coords), chunk_size):
            chunk = new_coords[i:i+chunk_size]
            chunk_results = rg.search(chunk, mode=1)  # mode=1: 单线程
            results.extend(chunk_results)

        # 更新缓存
        for i, key in enumerate(new_keys):
            try:
                country_code = results[i]['cc']
                continent_code = pc.country_alpha2_to_continent_code(country_code)
                geo_cache[key] = continent_code
            except:
                geo_cache[key] = 'Unknown'

    # 映射大洲代码到大洲名称
    continent_map = {
        'AF': 'Africa',
        'AS': 'Asia',
        'EU': 'Europe',
        'NA': 'North America',
        'SA': 'South America',
        'OC': 'Oceania'
    }

    # 分配大洲
    df['continent'] = [continent_map.get(geo_cache.get(k, 'Unknown'), 'Unknown')
                       for k in coords_keys]

    return df


def prepare_ratio_heatmap_data(
    crops=['rice', 'wheat', 'maize'],
    outday='20251028',
    indicators=['Y', 'ET', 'WUE', 'CH4', 'N2O', 'GWP']
):
    """
    准备六大洲比值热力图数据

    参数:
        crops: 作物列表
        outday: 输出日期标识
        indicators: 指标列表

    返回:
        data_dict: {crop: DataFrame} 字典
        每个DataFrame: 行=六大洲, 列=六大指标, 值=optimal_ck_ratio平均值
    """
    data_dict = {}
    geo_cache = {}  # 地理编码缓存（跨作物共享）

    for crop in crops:
        print(f"\n处理作物: {crop}")

        # 路径
        base_path = Path(f'E:/USERS/优化/results/{crop}/{outday}/W/spatial_analysis/comparison')

        # 合并所有指标的数据
        all_data = []

        for indicator in indicators:
            csv_file = base_path / f'{indicator}_comparison.csv'

            if not csv_file.exists():
                print(f"  警告: {indicator} 数据文件不存在")
                continue

            # 读取数据
            df = pd.read_csv(csv_file)

            # 添加指标列
            df['indicator'] = indicator

            # 检查ratio列：优先使用optimal_ck_ratio，如果不存在则计算optimal/ck
            if 'optimal_ck_ratio' in df.columns:
                ratio_col = 'optimal_ck_ratio'
            elif 'optimal' in df.columns and 'ck' in df.columns:
                # 计算ratio
                df['optimal_ck_ratio'] = df['optimal'] / df['ck']
                ratio_col = 'optimal_ck_ratio'
            else:
                print(f"  警告: {indicator} 数据文件缺少必要的ratio列")
                continue

            all_data.append(df[['x', 'y', 'indicator', ratio_col]])

        if not all_data:
            print(f"  错误: 作物 {crop} 无有效数据")
            continue

        # 合并
        merged_df = pd.concat(all_data, ignore_index=True)
        print(f"  总网格数: {len(merged_df):,}")

        # 分配大洲（动态地理编码）
        merged_df = assign_continent_dynamic(merged_df, geo_cache)

        # 统计各大洲网格数
        continent_counts = merged_df['continent'].value_counts()
        print(f"  大洲分布:")
        for continent in ['Africa', 'Asia', 'Europe', 'North America', 'South America', 'Oceania']:
            count = continent_counts.get(continent, 0)
            print(f"    {continent}: {count:,} 网格")

        # 构建矩阵：按大洲和指标分组
        heatmap_data = merged_df.groupby(['continent', 'indicator'])['optimal_ck_ratio'].mean().unstack()

        # 确保六大洲和六大指标都有
        continents = ['Africa', 'Asia', 'Europe', 'North America', 'Oceania', 'South America']
        heatmap_data = heatmap_data.reindex(index=continents, columns=indicators)

        data_dict[crop] = heatmap_data

        print(f"  热力图矩阵:")
        print(heatmap_data.round(3))

    return data_dict


